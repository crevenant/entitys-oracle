import { test, expect } from '@playwright/test'
import { catalog } from '../src/lib/oracle'
import type { Draw } from '../src/lib/oracle'

test('perk selection persists, blocks undersized pools, and stays separate by role', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('oracle:preferences', JSON.stringify({ motion: 'reduced' })))
  await page.goto('/')
  const pool = catalog.perks.filter((entry) => entry.role === 'survivor').slice(0, 4)
  await page.getByRole('button', { name: 'Options', exact: true }).click()
  await page.getByRole('button', { name: 'Collection', exact: true }).click()
  await page.getByRole('tab', { name: /Perks/ }).click()
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  for (const entry of pool.slice(0, 3)) {
    await page.getByRole('textbox', { name: 'Search perks' }).fill(entry.name)
    await page.getByRole('button', { name: entry.name, exact: true }).click()
  }
  await expect(page.getByRole('status').filter({ hasText: '3 of' })).toContainText('Choose at least four perks')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.getByRole('button', { name: 'Seal your fate' })).toBeDisabled()
  await page.getByRole('button', { name: 'Choose at least four perks' }).click()
  await page.getByRole('textbox', { name: 'Search perks' }).fill(pool[3].name)
  await page.getByRole('button', { name: pool[3].name, exact: true }).click()
  await page.getByRole('textbox', { name: 'Search perks' }).fill('')
  await page.screenshot({ path: `output/screenshots/${testInfo.project.name}-perk-pool.png`, fullPage: true })
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  const names = await page.locator('.perk-tile strong').allTextContents()
  expect(names.sort()).toEqual(pool.map((entry) => entry.name).sort())
  await page.reload()
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  expect((await page.locator('.perk-tile strong').allTextContents()).sort()).toEqual(names)
  await page.getByRole('button', { name: 'Killer', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Seal your fate' })).toBeEnabled()
  await page.getByRole('button', { name: 'Options', exact: true }).click()
  await page.getByRole('button', { name: 'Collection', exact: true }).click()
  await page.getByRole('tab', { name: /Perks/ }).click()
  const killerCount = catalog.perks.filter((entry) => entry.role === 'killer').length
  await expect(page.locator('.collection-count')).toContainText(`${killerCount} of ${killerCount}`)
  await page.getByRole('button', { name: 'Close dialog' }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('locks survive rerolls in their slots and exclusion releases a locked perk', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('oracle:preferences', JSON.stringify({ motion: 'reduced' })))
  await page.goto('/')
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  const latest = () => page.evaluate<Draw>(() => JSON.parse(localStorage.getItem('oracle:history')!)[0])
  const first = await latest()
  await page.getByRole('button', { name: 'Lock character', exact: true }).click()
  await page.getByRole('button', { name: /^Lock perk slot 1:/ }).click()
  await page.getByRole('button', { name: /^Lock perk slot 3:/ }).click()
  await expect(page.getByRole('button', { name: 'Unlock character', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.locator('.loadout').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `output/screenshots/${testInfo.project.name}-locked-loadout.png`, fullPage: true })
  await page.getByRole('button', { name: 'Reroll unlocked' }).click()
  const second = await latest()
  expect(second.character.id).toBe(first.character.id)
  expect(second.perks[0].id).toBe(first.perks[0].id)
  expect(second.perks[2].id).toBe(first.perks[2].id)
  expect(new Set(second.perks.map((entry) => entry.id)).size).toBe(4)
  await page.getByRole('button', { name: 'Edit perk pool' }).click()
  await page.getByRole('textbox', { name: 'Search perks' }).fill(first.perks[0].name)
  await page.getByRole('tabpanel', { name: /Perks/ }).getByRole('button', { name: first.perks[0].name, exact: true }).click()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await expect(page.getByRole('button', { name: /^Lock perk slot 1:/ })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.getByRole('button', { name: /^Unlock perk slot 3:/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Reroll unlocked' }).click()
  const third = await latest()
  expect(third.perks.some((entry) => entry.id === first.perks[0].id)).toBe(false)
  expect(third.perks[2].id).toBe(first.perks[2].id)
  await page.getByRole('button', { name: 'Options', exact: true }).click()
  await page.getByRole('button', { name: 'Past fates' }).click()
  await page.locator('.history-list button').last().click()
  await expect(page.getByRole('button', { name: 'Lock character', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: /^Lock perk slot 1:/ }).click()
  await page.getByRole('button', { name: 'Edit perk pool' }).click()
  await page.getByRole('textbox', { name: 'Search perks' }).fill(first.perks[0].name)
  await expect(page.getByRole('tabpanel', { name: /Perks/ }).getByRole('button', { name: first.perks[0].name, exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('all-lock recovery and role changes release locks without losing pool selections', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('oracle:preferences', JSON.stringify({ motion: 'reduced' })))
  await page.goto('/')
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  await page.getByRole('button', { name: 'Lock character', exact: true }).click()
  for (let slot = 1; slot <= 4; slot++) await page.getByRole('button', { name: new RegExp(`^Lock perk slot ${slot}:`) }).click()
  await expect(page.getByRole('button', { name: 'All entries locked' })).toBeDisabled()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('oracle:history')!).length)).toBe(1)
  await page.getByRole('button', { name: 'Release all locks' }).click()
  await expect(page.getByRole('button', { name: 'Tempt fate again' })).toBeEnabled()
  await page.getByRole('button', { name: 'Lock character', exact: true }).click()
  await page.getByRole('button', { name: /^Lock perk slot 2:/ }).click()
  await page.getByRole('button', { name: 'Killer', exact: true }).click()
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  await expect(page.getByRole('button', { name: 'Lock character', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.perk-lock[aria-pressed=true]')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('oracle:history')!)[0].character.role)).toBe('killer')
})

test('collection tabs support the keyboard and pools cannot change during a ritual', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Seal your fate' }).click()
  await page.getByRole('button', { name: 'Options', exact: true }).click()
  await page.getByRole('button', { name: 'Collection', exact: true }).click()
  await expect(page.getByText('Finish or skip the ritual before changing your pool.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Clear', exact: true })).toBeDisabled()
  await page.getByRole('tab', { name: /Characters/ }).press('ArrowRight')
  await expect(page.getByRole('tab', { name: /Perks/ })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.collection-perk').first()).toBeDisabled()
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Skip the ritual' }).click()
  await expect(page.getByRole('button', { name: 'Lock character', exact: true })).toBeEnabled()
})
